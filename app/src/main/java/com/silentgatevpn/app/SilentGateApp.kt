class SilentGateApp : Application() {

    companion object {
        /**
         * True on budget / old phones (low-RAM or Android 7.0 to 9): every VPN subsystem uses fewer parallel sockets,
         * smaller downloads and more forgiving time limits. The default is safe before [onCreate] has run.
         */
        @Volatile
        var isLowEndDevice: Boolean = Build.VERSION.SDK_INT < 29
            private set
    }

    override fun onCreate() {
        super.onCreate()
        isLowEndDevice = Build.VERSION.SDK_INT < 29 ||
            runCatching { (getSystemService(Context.ACTIVITY_SERVICE) as ActivityManager).isLowRamDevice }.getOrDefault(false)
        // TLS 1.3 + modern root CAs for every HttpURLConnection (feeds, probes, DoH). Must run before any download.
        installModernTls()
        SettingsStore.init(this)
        ProfileStore.init(this)
        PrimaryServer.init(this)
        NodePool.init(File(filesDir, "pool").apply { mkdirs() })
        // Last-resort home country if the live check fails: the SIM / network country, then Pakistan.
        runCatching {
            val tm = getSystemService(Context.TELEPHONY_SERVICE) as TelephonyManager
            val cc = tm.networkCountryIso.ifEmpty { tm.simCountryIso }
            if (cc.length == 2) Net.defaultHomeCc = cc.uppercase()
        }
        // Keep the node list fresh in the background (not on the main thread). First-time users get the same
        // pre-warm the moment they accept the welcome screen (see ConsentScreen).
        if (SettingsStore.value.consented) NodePool.prewarm()
        runCatching {
            val work = File(filesDir, "work").apply { mkdirs() }
            val opts = SetupOptions()
            opts.setBasePath(filesDir.path)
            opts.setWorkingPath(work.path)
            opts.setTempPath(cacheDir.path)
            opts.setFixAndroidStack(Build.VERSION.SDK_INT > Build.VERSION_CODES.M && Build.VERSION.SDK_INT < Build.VERSION_CODES.Q)
            opts.setLogMaxLines(500L)
            opts.setDebug(false)
            Libbox.setup(opts)
        }.onFailure { VpnState.log("Core setup failed: ${it.message}") }
    }

    // ------------------------------------------------------------------ TLS for Android 7.0 to 8.1

    /**
     * Android 7.0 to 8.1 ship a 2016 to 2018 TLS stack and root store: no TLS 1.3 and no ISRG / GTS / DigiCert G2-G3
     * roots, so HTTPS to GitHub, jsDelivr and Cloudflare fails. Conscrypt is bundled and installed first; below
     * Android 10 the default HTTPS socket factory also trusts the device store PLUS the bundled modern roots.
     * Certificate verification stays ON (nothing is trusted blindly).
     */
    private fun installModernTls() {
        val provider: Provider? = runCatching {
            if (Conscrypt.isAvailable()) Conscrypt.newProvider().also { Security.insertProviderAt(it, 1) } else null
        }.onFailure { VpnState.log("Conscrypt unavailable: ${it.message}") }.getOrNull()

        if (Build.VERSION.SDK_INT >= 29) return
        runCatching {
            val managers = listOfNotNull(systemTrustManager(), bundledTrustManager())
            if (managers.isEmpty()) return@runCatching
            fun ctx(alg: String): SSLContext = if (provider != null) SSLContext.getInstance(alg, provider) else SSLContext.getInstance(alg)
            val ssl = listOf("TLS", "TLSv1.3", "TLSv1.2").firstNotNullOfOrNull { runCatching { ctx(it) }.getOrNull() } ?: ctx("TLS")
            ssl.init(null, arrayOf<TrustManager>(CompositeTrustManager(managers)), null)
            HttpsURLConnection.setDefaultSSLSocketFactory(ssl.socketFactory)
            runCatching { SSLContext.setDefault(ssl) }
        }.onFailure { VpnState.log("Extra root certificates not installed: ${it.message}") }
    }

    private fun trustManagerFor(store: KeyStore?): X509TrustManager? = runCatching {
        val f = TrustManagerFactory.getInstance(TrustManagerFactory.getDefaultAlgorithm())
        f.init(store)
        f.trustManagers.filterIsInstance<X509TrustManager>().firstOrNull()
    }.getOrNull()

    /** The device's own root store (AndroidCAStore, includes roots the user installed). */
    private fun systemTrustManager(): X509TrustManager? {
        val store = runCatching { KeyStore.getInstance("AndroidCAStore").apply { load(null) } }.getOrNull()
        return trustManagerFor(store) ?: trustManagerFor(null)
    }

    /** Only the bundled modern roots; consulted when the device store cannot build the chain. */
    private fun bundledTrustManager(): X509TrustManager? {
        val cf = CertificateFactory.getInstance("X.509")
        val store = KeyStore.getInstance(KeyStore.getDefaultType()).apply { load(null, null) }
        var added = 0
        MODERN_ROOTS.forEachIndexed { i, pem ->
            runCatching {
                val cert = cf.generateCertificate(ByteArrayInputStream(pem.toByteArray(Charsets.US_ASCII))) as X509Certificate
                store.setCertificateEntry("sg-root-$i", cert)
                added++
            }
        }
        return if (added == 0) null else trustManagerFor(store)
    }

    /** Accepts a chain if ANY wrapped manager accepts it; reports the first manager's error otherwise. */
    private class CompositeTrustManager(private val managers: List<X509TrustManager>) : X509TrustManager {
        override fun checkClientTrusted(chain: Array<out X509Certificate>?, authType: String?) {
            managers.first().checkClientTrusted(chain, authType)
        }

        override fun checkServerTrusted(chain: Array<out X509Certificate>?, authType: String?) {
            var first: CertificateException? = null
            for (m in managers) {
                try {
                    m.checkServerTrusted(chain, authType)
                    return
                } catch (e: CertificateException) {
                    if (first == null) first = e
                }
            }
            throw first ?: CertificateException("No trust manager available")
        }

        override fun getAcceptedIssuers(): Array<X509Certificate> =
            managers.flatMap { it.acceptedIssuers.asList() }.toTypedArray()
    }

